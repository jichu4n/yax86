#!/usr/bin/env node

const fs = require('fs/promises');
const path = require('path');

// Embeds a binary image in a C array and header.
//
// Arguments:
// - symbol: Base name for identifiers.
// - moduleName (optional): Target core module (e.g. "bios").
//   - If provided: The identifiers are in the core's namespace, which AGENTS.md
//     describes under "Naming", so symbol must begin with the module's owner:
//     BIOSROMData -> YBIOSROMData, Y_BIOS_ROM_DATA_SIZE. The array is marked
//     Y_MODULE_PRIVATE (static in bundled builds) and the header's extern
//     declaration is suppressed inside the bundle.
//   - If omitted: Generated as a standalone translation unit with external
//     linkage (e.g. for the pico/bench boot floppy image), and the identifiers
//     are the caller's own: DOSFloppyData -> kDOSFloppyData, kDOSFloppyDataSize.
// The identifiers for a module's ROM, in the module's namespace. The owner is
// the leading part of symbol that spells the module's name, so BIOSROMData in
// bios is the owner BIOS and the words ROM and Data. A run of capitals is one
// word, which is what keeps ROM apart from Data; splitting the owner off first
// is what keeps it apart from ROM.
function namespacedSymbols(symbol, moduleName) {
  const owner = symbol.slice(0, moduleName.length);
  const rest = symbol.slice(moduleName.length);
  if (owner.toLowerCase() !== moduleName.toLowerCase() || !/^[A-Z]/.test(rest)) {
    throw new Error(
      `${symbol} must begin with the owner of module ${moduleName}, ` +
        `as BIOSROMData does for bios`,
    );
  }
  const words = rest.match(/[A-Z]+(?![a-z])|[A-Z][a-z]*|[0-9]+/g);
  return {
    dataSymbol: `Y${symbol}`,
    sizeSymbol: `Y_${[owner, ...words, 'Size'].join('_').toUpperCase()}`,
  };
}

async function generateRomDataFiles(romFilePath, outputFilePath, symbol, moduleName) {
  const romContent = await fs.readFile(romFilePath);

  const {dataSymbol, sizeSymbol} = moduleName
    ? namespacedSymbols(symbol, moduleName)
    : {dataSymbol: `k${symbol}`, sizeSymbol: `k${symbol}Size`};
  const headerGuard = `YAX86_${path.basename(outputFilePath).toUpperCase()}_H`;
  const banner = [
    `// ROM data automatically generated by ${path.basename(__filename)}`,
    `// Source: ${path.basename(romFilePath)}`,
    '',
  ];

  let headerDeclaration;
  let sourcePreamble;
  let definitionModifier;

  if (moduleName) {
    const bundleGuard = `YAX86_${moduleName.toUpperCase()}_BUNDLE_H`;
    headerDeclaration = [
      '// In unbundled builds, external callers within the module need an extern',
      '// declaration. In bundled builds, the array is static and defined earlier in',
      '// the same translation unit (via bundle.json), so an extern declaration',
      '// would conflict and is omitted.',
      `#ifndef ${bundleGuard}`,
      `extern const uint8_t ${dataSymbol}[${sizeSymbol}];`,
      `#endif // ${bundleGuard}`,
    ];
    sourcePreamble = [
      `#ifndef ${bundleGuard}`,
      '#include "../util/common.h"',
      `#endif // ${bundleGuard}`,
      '',
    ];
    definitionModifier = 'Y_MODULE_PRIVATE ';
  } else {
    headerDeclaration = [`extern const uint8_t ${dataSymbol}[${sizeSymbol}];`];
    sourcePreamble = [];
    definitionModifier = '';
  }

  const hContent = [
    ...banner,
    `#ifndef ${headerGuard}`,
    `#define ${headerGuard}`,
    '',
    '#include <stdint.h>',
    '',
    'enum {',
    `  ${sizeSymbol} = ` + romContent.length + ',',
    '};',
    '',
    ...headerDeclaration,
    '',
    `#endif // ${headerGuard}`,
    '',
  ].join('\n');
  await fs.writeFile(`${outputFilePath}.h`, hContent, 'utf8');

  const cContent = [
    ...banner,
    '#include <stdint.h>',
    '',
    ...sourcePreamble,
    `${definitionModifier}const uint8_t ${dataSymbol}[] = {`,
    Array.from(romContent)
      .map(
        (byte, index) =>
          (index % 16 === 0 && index > 0 ? `\n` : '') +
          `0x${byte.toString(16).padStart(2, '0')},`
      )
      .join(''),
    '};',
    '',
  ].join('\n');
  await fs.writeFile(`${outputFilePath}.c`, cContent, 'utf8');
}

const usage = [
  'Usage: generate-rom-data-files.js <input.rom> <output_prefix> <symbol>',
  '                                  [--module <name>]',
  '',
  'Options:',
  '  --module <name>  Target core module (e.g. "bios"). Generates a module-private',
  '                   array for header bundles. Omit for standalone objects with',
  '                   external linkage (e.g. pico/bench boot floppy).',
].join('\n');

if (require.main === module) {
  const args = process.argv.slice(2);
  const positional = [];
  let moduleName;
  for (let i = 0; i < args.length; ++i) {
    if (args[i] === '--module') {
      moduleName = args[++i];
      if (!moduleName) {
        console.error('--module needs a module name\n\n' + usage);
        process.exit(1);
      }
    } else if (args[i].startsWith('--')) {
      console.error(`Unknown option ${args[i]}\n\n` + usage);
      process.exit(1);
    } else {
      positional.push(args[i]);
    }
  }
  if (positional.length !== 3) {
    console.error(usage);
    process.exit(1);
  }
  const [romFilePath, outputFilePath, symbol] = positional;

  generateRomDataFiles(romFilePath, outputFilePath, symbol, moduleName).catch(
    (e) => {
      console.error(e.message);
      process.exit(1);
    },
  );
}
