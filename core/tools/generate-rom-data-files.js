#!/usr/bin/env node

const fs = require('fs/promises');
const path = require('path');

// Embeds a ROM image in a C source file and its header, so that ROMs are
// compiled into the library rather than read from a file at run time. Targets
// like the Raspberry Pi Pico have no file system to read one from.
//
// The symbol argument names the generated array, so BIOSROMData produces
// kBIOSROMData and kBIOSROMDataSize. If module is supplied (e.g. "bios"),
// the array is marked YAX86_MODULE_PRIVATE and guarded by the module's
// bundle guard (e.g. YAX86_BIOS_BUNDLE_H); otherwise, it is generated as
// a standalone data file with plain external linkage (used by the Pico bench).
async function generateRomDataFiles(romFilePath, outputFilePath, symbol, moduleName) {
  const romContent = await fs.readFile(romFilePath);

  const dataSymbol = `k${symbol}`;
  const sizeSymbol = `k${symbol}Size`;
  const headerGuard = `YAX86_${path.basename(outputFilePath).toUpperCase()}_H`;
  const banner = [
    `// ROM data automatically generated by ${path.basename(__filename)}`,
    `// Source: ${path.basename(romFilePath)}`,
    '',
  ];

  let headerDeclaration;
  let sourcePreamble;
  let definitionModifier;

  if (moduleName) {
    const bundleGuard = `YAX86_${moduleName.toUpperCase()}_BUNDLE_H`;
    headerDeclaration = [
      '// A data declaration has no spelling that works in both configurations,',
      '// so this one is visible only when unbundled. `extern` is what an',
      '// unbundled caller needs, and conflicts with the static definition once',
      '// bundled. The bundled build reaches the array by position instead, so',
      '// the generated source precedes its users in bundle.json.',
      `#ifndef ${bundleGuard}`,
      `extern const uint8_t ${dataSymbol}[${sizeSymbol}];`,
      `#endif // ${bundleGuard}`,
    ];
    sourcePreamble = [
      `#ifndef ${bundleGuard}`,
      '#include "../util/common.h"',
      `#endif // ${bundleGuard}`,
      '',
    ];
    definitionModifier = 'YAX86_MODULE_PRIVATE ';
  } else {
    headerDeclaration = [`extern const uint8_t ${dataSymbol}[${sizeSymbol}];`];
    sourcePreamble = [];
    definitionModifier = '';
  }

  const hContent = [
    ...banner,
    `#ifndef ${headerGuard}`,
    `#define ${headerGuard}`,
    '',
    '#include <stdint.h>',
    '',
    'enum {',
    `  ${sizeSymbol} = ` + romContent.length + ',',
    '};',
    '',
    ...headerDeclaration,
    '',
    `#endif // ${headerGuard}`,
    '',
  ].join('\n');
  await fs.writeFile(`${outputFilePath}.h`, hContent, 'utf8');

  const cContent = [
    ...banner,
    '#include <stdint.h>',
    '',
    ...sourcePreamble,
    `${definitionModifier}const uint8_t ${dataSymbol}[] = {`,
    Array.from(romContent)
      .map(
        (byte, index) =>
          (index % 16 === 0 && index > 0 ? `\n` : '') +
          `0x${byte.toString(16).padStart(2, '0')},`
      )
      .join(''),
    '};',
    '',
  ].join('\n');
  await fs.writeFile(`${outputFilePath}.c`, cContent, 'utf8');
}

if (require.main === module) {
  const args = process.argv.slice(2);
  if (args.length < 3) {
    console.error(
      'Usage: generate-rom-data-files.js XXX.rom output_file_prefix symbol [module]'
    );
    process.exit(1);
  }
  const [romFilePath, outputFilePath, symbol, moduleName] = args;

  (async () => {
    await generateRomDataFiles(romFilePath, outputFilePath, symbol, moduleName);
  })();
}
