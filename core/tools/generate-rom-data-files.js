#!/usr/bin/env node

const fs = require('fs/promises');
const path = require('path');

// Embeds a binary image in a C array and header.
//
// Arguments:
// - symbol: Base name for identifiers (e.g. BIOSROMData -> kBIOSROMData, kBIOSROMDataSize).
// - moduleName (optional): Target core module (e.g. "bios").
//   - If provided: The array is marked YAX86_MODULE_PRIVATE (static in bundled
//     builds) and the header's extern declaration is suppressed inside the bundle.
//   - If omitted: Generated as a standalone translation unit with external
//     linkage (e.g. for the pico/bench boot floppy image).
async function generateRomDataFiles(romFilePath, outputFilePath, symbol, moduleName) {
  const romContent = await fs.readFile(romFilePath);

  const dataSymbol = `k${symbol}`;
  const sizeSymbol = `k${symbol}Size`;
  const headerGuard = `YAX86_${path.basename(outputFilePath).toUpperCase()}_H`;
  const banner = [
    `// ROM data automatically generated by ${path.basename(__filename)}`,
    `// Source: ${path.basename(romFilePath)}`,
    '',
  ];

  let headerDeclaration;
  let sourcePreamble;
  let definitionModifier;

  if (moduleName) {
    const bundleGuard = `YAX86_${moduleName.toUpperCase()}_BUNDLE_H`;
    headerDeclaration = [
      '// In unbundled builds, external callers within the module need an extern',
      '// declaration. In bundled builds, the array is static and defined earlier in',
      '// the same translation unit (via bundle.json), so an extern declaration',
      '// would conflict and is omitted.',
      `#ifndef ${bundleGuard}`,
      `extern const uint8_t ${dataSymbol}[${sizeSymbol}];`,
      `#endif // ${bundleGuard}`,
    ];
    sourcePreamble = [
      `#ifndef ${bundleGuard}`,
      '#include "../util/common.h"',
      `#endif // ${bundleGuard}`,
      '',
    ];
    definitionModifier = 'YAX86_MODULE_PRIVATE ';
  } else {
    headerDeclaration = [`extern const uint8_t ${dataSymbol}[${sizeSymbol}];`];
    sourcePreamble = [];
    definitionModifier = '';
  }

  const hContent = [
    ...banner,
    `#ifndef ${headerGuard}`,
    `#define ${headerGuard}`,
    '',
    '#include <stdint.h>',
    '',
    'enum {',
    `  ${sizeSymbol} = ` + romContent.length + ',',
    '};',
    '',
    ...headerDeclaration,
    '',
    `#endif // ${headerGuard}`,
    '',
  ].join('\n');
  await fs.writeFile(`${outputFilePath}.h`, hContent, 'utf8');

  const cContent = [
    ...banner,
    '#include <stdint.h>',
    '',
    ...sourcePreamble,
    `${definitionModifier}const uint8_t ${dataSymbol}[] = {`,
    Array.from(romContent)
      .map(
        (byte, index) =>
          (index % 16 === 0 && index > 0 ? `\n` : '') +
          `0x${byte.toString(16).padStart(2, '0')},`
      )
      .join(''),
    '};',
    '',
  ].join('\n');
  await fs.writeFile(`${outputFilePath}.c`, cContent, 'utf8');
}

const usage = [
  'Usage: generate-rom-data-files.js <input.rom> <output_prefix> <symbol>',
  '                                  [--module <name>]',
  '',
  'Options:',
  '  --module <name>  Target core module (e.g. "bios"). Generates a module-private',
  '                   array for header bundles. Omit for standalone objects with',
  '                   external linkage (e.g. pico/bench boot floppy).',
].join('\n');

if (require.main === module) {
  const args = process.argv.slice(2);
  const positional = [];
  let moduleName;
  for (let i = 0; i < args.length; ++i) {
    if (args[i] === '--module') {
      moduleName = args[++i];
      if (!moduleName) {
        console.error('--module needs a module name\n\n' + usage);
        process.exit(1);
      }
    } else if (args[i].startsWith('--')) {
      console.error(`Unknown option ${args[i]}\n\n` + usage);
      process.exit(1);
    } else {
      positional.push(args[i]);
    }
  }
  if (positional.length !== 3) {
    console.error(usage);
    process.exit(1);
  }
  const [romFilePath, outputFilePath, symbol] = positional;

  (async () => {
    await generateRomDataFiles(romFilePath, outputFilePath, symbol, moduleName);
  })();
}
