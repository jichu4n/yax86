#!/usr/bin/env node

const fs = require('fs/promises');
const path = require('path');

// Embeds a ROM image in a C source file and its header, so that ROMs are
// compiled into the library rather than read from a file at run time. Targets
// like the Raspberry Pi Pico have no file system to read one from.
//
// The symbol argument names the generated array, so BIOSROMData produces
// kBIOSROMData and kBIOSROMDataSize. The include guard comes from the output
// file name and the bundle guard from the module directory, so
// src/bios/bios_rom_data yields YAX86_BIOS_ROM_DATA_H and YAX86_BIOS_BUNDLE.
async function generateRomDataFiles(romFilePath, outputFilePath, symbol) {
  const romContent = await fs.readFile(romFilePath);

  const dataSymbol = `k${symbol}`;
  const sizeSymbol = `k${symbol}Size`;
  const headerGuard = `YAX86_${path.basename(outputFilePath).toUpperCase()}_H`;
  const bundleGuard = `YAX86_${path
    .basename(path.dirname(outputFilePath))
    .toUpperCase()}_BUNDLE`;
  const banner = [
    `// ROM data automatically generated by ${path.basename(__filename)}`,
    `// Source: ${path.basename(romFilePath)}`,
    '',
  ];

  const hContent = [
    ...banner,
    `#ifndef ${headerGuard}`,
    `#define ${headerGuard}`,
    '',
    '#include <stdint.h>',
    '',
    'enum {',
    `  ${sizeSymbol} = ` + romContent.length + ',',
    '};',
    '',
    `#ifndef ${bundleGuard}`,
    `extern const uint8_t ${dataSymbol}[${sizeSymbol}];`,
    `#endif // ${bundleGuard}`,
    '',
    `#endif // ${headerGuard}`,
    '',
  ].join('\n');
  await fs.writeFile(`${outputFilePath}.h`, hContent, 'utf8');

  const cContent = [
    ...banner,
    '#include <stdint.h>',
    '',
    `const uint8_t ${dataSymbol}[] = {`,
    Array.from(romContent)
      .map(
        (byte, index) =>
          (index % 16 === 0 && index > 0 ? `\n` : '') +
          `0x${byte.toString(16).padStart(2, '0')},`
      )
      .join(''),
    '};',
    '',
  ].join('\n');
  await fs.writeFile(`${outputFilePath}.c`, cContent, 'utf8');
}

if (require.main === module) {
  const args = process.argv.slice(2);
  if (args.length < 3) {
    console.error(
      'Usage: generate-rom-data-files.js XXX.rom output_file_prefix symbol'
    );
    process.exit(1);
  }
  const [romFilePath, outputFilePath, symbol] = args;

  (async () => {
    await generateRomDataFiles(romFilePath, outputFilePath, symbol);
  })();
}
