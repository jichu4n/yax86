//   is reproduced below.
// - The rest of code page 437, including every box drawing, block and shade
//   character, and the reworked 0, m and w: Copyright (c) 2026 Serg Podtynnyi,
//   GPL-3.0-or-later, https://github.com/shtirlic/picocalc_x86 (0ac7231).
//
// Every glyph outside the box drawing range sits one row lower than in the
// source table, which leaves a blank row between lines of text while box
// drawing characters fill the cell and join up. The source left that shift to
// its renderer; here it is in the table, so that any renderer can draw it as a
// plain font. The three glyphs that use the bottom row - 0x02, 0x0F and 0x16,
