// A 4x10 font covering all 256 characters of code page 437.
//
// The glyphs are three pixels wide with a one pixel gap, which is what lets
// 80 columns fit across a 320 pixel panel. Shrinking an 8 pixel font to fit
// instead makes text unreadable, so an 80 column display this narrow needs a
// font drawn for it.
//
// Provenance:
//
// - The ASCII glyphs, 0x00-0x81, are from picocalc_runCPM
//   (https://github.com/theflynn49/picocalc_runCPM), contributed by rugosi in
//   "Adding 4x10 font for 80 columns" (f4d6859, 2025). MIT licensed; the notice
//   is reproduced below.
// - The rest of code page 437, including every box drawing, block and shade
//   character, and the reworked 0, m and w: Copyright (c) 2026 Serg Podtynnyi,
//   GPL-3.0-or-later, https://github.com/shtirlic/picocalc_x86 (0ac7231).
//
// Every glyph outside the box drawing range sits one row lower than in the
// source table, which leaves a blank row between lines of text while box
// drawing characters fill the cell and join up. The source left that shift to
// its renderer; here it is in the table, so that any renderer can draw it as a
// plain font. The three glyphs that use the bottom row - 0x02, 0x0F and 0x16,
// which are cell-filling patterns - are left where they are, so that the shift
// does not clip them.
